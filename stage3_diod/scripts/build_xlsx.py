def sheet(name, widths):
    ws = wb.create_sheet(name)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[CL(i)].width = w
    ws.sheet_view.showGridLines = False
    return ws


def W(ws, ref, v, kind='f', fmt=None, bold=False, fill=None, al=None, border=True):
    c = ws[ref]
    c.value = v
    c.font = {'in': f_in, 'link': f_link, 'f': f_norm, 'b': f_b, 'note': f_note, 'title': f_title, 'hdr': f_hdr}[kind]
    if bold and kind in ('f', 'in', 'link'):
        c.font = Font(name=F, size=10, bold=True, color=c.font.color)
    if fmt:
        c.number_format = fmt
    if fill:
        c.fill = fill
    if al:
        c.alignment = al
    if border and kind not in ('title', 'note'):
        c.border = bord
    return c


def header(ws, row, vals, col=1, height=None):
    for i, v in enumerate(vals):
        c = ws.cell(row=row, column=col + i, value=v)
        c.font = f_hdr; c.fill = fill_hdr; c.alignment = center; c.border = bord
    if height:
        ws.row_dimensions[row].height = height


def section(ws, row, text, ncol):
    for i in range(1, ncol + 1):
        c = ws.cell(row=row, column=i)
        c.fill = fill_sec; c.border = bord
    c = ws.cell(row=row, column=1, value=text); c.font = f_b


def title(ws, text, sub=None):
    W(ws, 'A1', text, 'title')
    if sub:
        W(ws, 'A2', sub, 'note')


def note(ws, ref, text):
    c = ws[ref]; c.value = text; c.font = f_note; c.alignment = Alignment(wrap_text=True, vertical='top')


